// Bundles the theme's LuCI JavaScript modules into preview/modules.js so the
// preview pages also work when opened straight from disk (file://), where
// browsers block fetch(). serve.js re-runs this automatically on every change.
//
//   node preview/build.js
const fs = require('fs'), path = require('path');

const RES = path.resolve(__dirname, '..', 'luci-theme-violet', 'htdocs', 'luci-static', 'resources');
const OUT = path.join(__dirname, 'modules.js');

function listModules() {
	const mods = [ [ 'menu-violet', path.join(RES, 'menu-violet.js') ] ];
	const incDir = path.join(RES, 'view', 'status', 'include');

	for (const f of fs.readdirSync(incDir).sort())
		if (/_violet_.*\.js$/.test(f))
			mods.push([ 'view.status.include.' + f.replace(/\.js$/, ''), path.join(incDir, f) ]);

	return mods;
}

function build() {
	const entries = listModules().map(([ name, file ]) =>
		`\t${JSON.stringify(name)}: ${JSON.stringify(fs.readFileSync(file, 'utf8'))}`);

	const out = '// Generated by preview/build.js - do not edit. Theme module sources for file:// previews.\n' +
		'window.VL_MODULES = {\n' + entries.join(',\n') + '\n};\n';

	fs.writeFileSync(OUT, out);
	return entries.length;
}

module.exports = { build, RES };

if (require.main === module)
	console.log(`preview/modules.js: ${build()} modules bundled`);
